#!/bin/sh
# SPDX-License-Identifier: MIT
# Make br2-external/configs/<board>_defconfig from the common fragment, the
# root fragment (flashroot or diskroot), and the board fragment.  With --check,
# change nothing and fail when a generated defconfig differs from its sources.
set -eu

cd "$(dirname "$0")/.."
frag=br2-external/board/esp32s31/defconfig
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
status=0

fragments_for()
{
	case $1 in
	esp32s31) echo "common kernel-default userspace-full flashroot esp32s31" ;;
	korvo1flash) echo "common headless-iot flashroot korvo1flash" ;;
	*) echo "common kernel-default userspace-full diskroot $1" ;;
	esac
}

check_flash()
{
	cfg=$1
	grep -q '^BR2_TARGET_ROOTFS_SQUASHFS=y$' "$cfg" || {
		echo "$cfg: flashroot squashfs is missing" >&2; exit 1; }
	if grep -q '^BR2_TARGET_ROOTFS_EXT2=y$' "$cfg"; then
		echo "$cfg: flash profile unexpectedly enables a disk root" >&2; exit 1
	fi
	if grep -Eq '^(BR2_PACKAGE_XORG7|BR2_PACKAGE_XSERVER_XORG_SERVER|BR2_PACKAGE_ICEWM|BR2_PACKAGE_MATCHBOX)=y$' "$cfg"; then
		echo "$cfg: X leaked into the headless flash profile" >&2; exit 1
	fi
	if grep -q '/openwrt' "$cfg"; then
		echo "$cfg: flash profile depends on the OpenWrt worktree" >&2; exit 1
	fi
}

for board in korvo1 esp32s31 coreboard1 korvo1flash; do
	fragments=$(fragments_for "$board")
	CONFIG_=BR2_ external/buildroot/support/kconfig/merge_config.sh -m -O "$tmp" \
		$(for f in $fragments; do echo "$frag/$f.fragment"; done) >"$tmp/log" 2>&1 ||
		{ cat "$tmp/log" >&2; exit 1; }
	if grep -q 'is redefined' "$tmp/log"; then
		grep -A2 'is redefined' "$tmp/log" >&2
		echo "$board: a setting is in two fragments" >&2
		exit 1
	fi
	{
		echo "# Generated by scripts/mkdefconfigs.sh.  Do not edit: change"
		echo "# $(echo $fragments | sed 's/ /.fragment, /g; s/\(.*\), /\1 and /').fragment in $frag/."
		cat "$tmp/.config"
	} >"$tmp/$board"
	[ "$board" != korvo1flash ] || check_flash "$tmp/$board"
	out=br2-external/configs/${board}_defconfig
	if [ "${1:-}" = --check ]; then
		cmp -s "$tmp/$board" "$out" ||
			{ echo "$out differs from its fragments: run make defconfigs" >&2; status=1; }
	else
		cp "$tmp/$board" "$out"
	fi
done

# ABI variants: <board>f = <board> + ilp32f.fragment.  The delta intentionally
# overrides the soft-float lines, so the base redefinition guard does not apply.
for board in korvo1 esp32s31 korvo1flash; do
	delta=$frag/ilp32f.fragment
	[ -f "$delta" ] || break
	fragments=$(fragments_for "$board")
	CONFIG_=BR2_ external/buildroot/support/kconfig/merge_config.sh -m -O "$tmp" \
		$(for f in $fragments; do echo "$frag/$f.fragment"; done) "$delta" >"$tmp/log" 2>&1 ||
		{ cat "$tmp/log" >&2; exit 1; }
	{
		echo "# Generated by scripts/mkdefconfigs.sh.  Do not edit: change"
		echo "# $(echo $fragments | sed 's/ /.fragment, /g').fragment and ilp32f.fragment in $frag/."
		cat "$tmp/.config"
	} >"$tmp/${board}f"
	grep -q '^BR2_RISCV_ABI_ILP32F=y$' "$tmp/${board}f" || {
		echo "${board}f: ILP32F is missing" >&2; exit 1; }
	grep -q '^# BR2_RISCV_ABI_ILP32 is not set$' "$tmp/${board}f" || {
		echo "${board}f: soft ILP32 was not explicitly disabled" >&2; exit 1; }
	if [ "$board" = korvo1 ]; then
		grep -q '^BR2_TARGET_ROOTFS_EXT2=y$' "$tmp/${board}f" || {
			echo 'korvo1f: diskroot EXT2 output is missing' >&2; exit 1; }
		grep -q '^BR2_PACKAGE_HOST_GENIMAGE=y$' "$tmp/${board}f" || {
			echo 'korvo1f: diskroot genimage support is missing' >&2; exit 1; }
	fi
	[ "$board" != korvo1flash ] || check_flash "$tmp/${board}f"
	out=br2-external/configs/${board}f_defconfig
	if [ "${1:-}" = --check ]; then
		cmp -s "$tmp/${board}f" "$out" ||
			{ echo "$out differs from its fragments: run make defconfigs" >&2; status=1; }
	else
		cp "$tmp/${board}f" "$out"
	fi
done
exit $status
